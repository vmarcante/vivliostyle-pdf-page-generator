import os
import asyncio
from pathlib import Path
from typing import List

# Tempo máximo (em segundos) aguardado pelo Vivliostyle antes de abortar.
# Configurável via variável de ambiente VIVLIO_TIMEOUT.
_VIVLIO_TIMEOUT = int(os.environ.get("VIVLIO_TIMEOUT", "120"))


def _js_array(items: List[str], indent: str = "  ") -> str:
    """Formata uma lista de strings como array JavaScript indentado."""
    inner = "\n".join(f"    './{item}'," for item in items)
    return f"[\n{inner}\n{indent}]"


def generate_config(workdir: Path) -> Path:
    """Gera um ``vivliostyle.config.js`` mínimo com base nos arquivos presentes.

    Ordem de entrada: ``cover.html`` (se existir) seguido dos demais HTMLs em
    ``src/``. Estilos em ``styles/*.css`` são usados como tema. Se não houver
    diretório ``src/``, os HTMLs da raiz do workspace são utilizados.
    """
    styles: List[str] = []
    styles_dir = workdir / "styles"
    if styles_dir.exists():
        for css in sorted(styles_dir.glob("*.css")):
            styles.append(str(css.relative_to(workdir)).replace("\\", "/"))

    entries: List[str] = []
    src_dir = workdir / "src"
    if src_dir.exists():
        htmls = sorted(src_dir.glob("*.html"))
        cover = src_dir / "cover.html"
        if cover.exists():
            entries.append(str(cover.relative_to(workdir)).replace("\\", "/"))
            htmls = [h for h in htmls if h.name != "cover.html"]
        for h in htmls:
            entries.append(str(h.relative_to(workdir)).replace("\\", "/"))
    if not entries:
        for h in sorted(workdir.glob("*.html")):
            entries.append(str(h.name))

    lines = [
        "/** Auto-generated by API */",
        "module.exports = {",
        "  size: 'A4',",
    ]
    if styles:
        lines.append(f"  theme: {_js_array(styles)},")
    lines.append(f"  entry: {_js_array(entries)}")
    lines.append("};")

    cfg = workdir / "vivliostyle.config.js"
    cfg.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return cfg


async def run_cli(workdir: Path, config_path: Path, output_pdf: Path) -> None:
    """Invoca o Vivliostyle CLI de forma assíncrona.

    Levanta ``RuntimeError`` se o CLI encerrar com código não-zero ou se
    ultrapassar ``_VIVLIO_TIMEOUT`` segundos.
    """
    # -s A4 é omitido pois o tamanho já está definido no vivliostyle.config.js
    cmd = ["vivliostyle", "build", "-c", str(config_path), "-o", str(output_pdf)]
    env = os.environ.copy()
    proc = await asyncio.create_subprocess_exec(
        *cmd,
        cwd=str(workdir),
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.STDOUT,
        env=env,
    )
    try:
        stdout, _ = await asyncio.wait_for(proc.communicate(), timeout=_VIVLIO_TIMEOUT)
    except asyncio.TimeoutError:
        proc.kill()
        await proc.wait()
        raise RuntimeError(f"Vivliostyle excedeu o tempo limite de {_VIVLIO_TIMEOUT}s")
    if proc.returncode != 0:
        raise RuntimeError(
            f"Vivliostyle falhou (exit {proc.returncode})\n"
            f"{stdout.decode(errors='ignore')}"
        )


def build_demo_project(workdir: Path) -> None:
    """Cria um projeto de demonstração mínimo no workspace fornecido."""
    (workdir / "src").mkdir(parents=True, exist_ok=True)
    (workdir / "styles").mkdir(parents=True, exist_ok=True)

    # Usa fontes do sistema — sem dependência de rede
    (workdir / "styles/base.css").write_text(
        "html, body {\n"
        "  margin: 0;\n"
        "  padding: 0;\n"
        "}\n"
        "body {\n"
        "  font-family: system-ui, -apple-system, Segoe UI, Roboto, Inter, sans-serif;\n"
        "  color: #111827;\n"
        "  line-height: 1.4;\n"
        "}\n",
        encoding="utf-8",
    )
    (workdir / "styles/print.css").write_text(
        "@page {\n"
        "  size: 210mm 297mm;\n"
        "  margin: 0;\n"
        "  marks: none;\n"
        "  bleed: 0;\n"
        "}\n",
        encoding="utf-8",
    )
    (workdir / "src/cover.html").write_text(
        "<!doctype html>\n"
        "<html>\n"
        "  <head><meta charset='utf-8'><title>Capa</title></head>\n"
        "  <body><h1>Demo</h1></body>\n"
        "</html>\n",
        encoding="utf-8",
    )
